const { chromium } = require('C:/Users/lenovo/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: 'C:/Users/lenovo/AppData/Local/ms-playwright/chromium-1248/chrome-win64/chrome.exe' });
  const base = 'http://127.0.0.1:8000/';
  const sign = base + 'industries/villa-projects.html';
  const menu = base + 'index.html?menu=industries&returnTo=industries%2Fvilla-projects.html';
  const results = [];
  for (const width of [390, 555, 1440]) {
    const page = await browser.newPage({ viewport: { width, height: width === 555 ? 668 : 900 } });
    page.setDefaultTimeout(10000);
    const back = page.locator('#industries-menu .mega-mobile-back');
    await page.goto(base + 'all-businesses.html');
    await page.goto(sign);
    await page.getByRole('link', { name: 'View all industries', exact: true }).click();
    await page.waitForURL(url => url.searchParams.get('menu') === 'industries');
    assert.equal(await page.locator('#industries-menu').evaluate(e => e.classList.contains('is-open')), true);
    await back.click();
    await page.waitForURL(sign);
    results.push({ width, test: 'View all industries → section Back → The Sign', pass: true });
    await page.locator('.history-back').click();
    await page.waitForURL(base + 'all-businesses.html');
    results.push({ width, test: 'The Sign Back does not loop through industries section', pass: true });
    await page.goto(sign);
    await page.getByRole('link', { name: 'View all industries', exact: true }).click();
    await page.waitForURL(url => url.searchParams.get('menu') === 'industries');
    await page.reload();
    await back.click();
    await page.waitForURL(sign);
    results.push({ width, test: 'Section Back still returns to The Sign after refresh', pass: true });
    await page.goto(base + 'index.html');
    if (await page.locator('.menu-toggle').isVisible()) await page.locator('.menu-toggle').click();
    await page.locator('.business-nav-trigger').click();
    await page.locator('#business-dropdown a').filter({ hasText: 'The Sign' }).click();
    await page.waitForURL(sign);
    await page.getByRole('link', { name: 'View all industries', exact: true }).evaluate(e => e.href = '../index.html?menu=industries');
    await page.getByRole('link', { name: 'View all industries', exact: true }).click();
    await page.waitForURL(url => url.searchParams.get('menu') === 'industries');
    await back.click();
    await page.waitForURL(sign);
    results.push({ width, test: 'Select The Sign → legacy View all industries URL → marked Back returns to The Sign', pass: true });
    await page.getByRole('link', { name: 'View all industries', exact: true }).evaluate(e => e.href = '../index.html?menu=industries');
    await page.getByRole('link', { name: 'View all industries', exact: true }).click();
    await page.waitForURL(url => url.searchParams.get('menu') === 'industries');
    await page.reload();
    await back.click();
    await page.waitForURL(sign);
    results.push({ width, test: 'Legacy return destination survives section refresh', pass: true });
    const direct = await browser.newPage({ viewport: { width, height: 900 } });
    await direct.goto(menu);
    await direct.locator('#industries-menu .mega-mobile-back').click();
    await direct.waitForURL(sign);
    results.push({ width, test: 'Direct menu URL has a working Sign return fallback', pass: true });
    await direct.close();
    await page.goto(base + 'index.html');
    if (await page.locator('.menu-toggle').isVisible()) await page.locator('.menu-toggle').click();
    await page.locator('[data-mega-target="industries-menu"]').click();
    await back.click();
    assert.equal(page.url(), base + 'index.html');
    assert.equal(await page.locator('#industries-menu').evaluate(e => e.classList.contains('is-open')), false);
    results.push({ width, test: 'Normal homepage industries Back retains original behavior', pass: true });
    await page.close();
  }
  fs.writeFileSync(path.join(__dirname, 'sign-navigation-results.json'), JSON.stringify(results, null, 2));
  console.log(JSON.stringify({ checks: results.length, results }, null, 2));
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
